def training_pairs():
    rows = []
    for name, topic, old, other, unchanged in SCENES:
        first = f'安排一下{name}，{topic}定为{old}，另外{unchanged}。'
        choices = (f'{topic}为{old}，仍需{unchanged}。', f'{topic}为{other}，仍需{unchanged}。')
        forms = (
            (f'也可以考虑{other}，这只是备选。',
             ('维持上一版正式安排，备选先放一放。', '备选转为正式安排，剩下的照常。')),
            (f'{topic}换成{other}，余下事项原样保留。',
             ('回退刚才的那一点，给我当前版本。', '刚才那一处修改照办，出最终版。')),
            (f'如果登记审核没过，则用{other}替补，其余不改。',
             ('审核过了，按计划出通知。', '审核未通过，发替补方案。')),
            (f'有人提到“{other}”这个说法，大家还在讨论。',
             ('引号内的词是被讨论的例子。还是照原方案。', '把引号内的建议落实到方案，其余照旧。')),
            (f'暂时用{other}替下原来那项，等最终确认。',
             ('负责人取消这次调整，其他不用动。', '负责人同意这次调整，其他不用动。')),
        )
        for index, (second, endings) in enumerate(forms):
            rows.append((f'{name}-{index}', (first, second), endings, choices))
        second = f'把{other}排在备选第一位，把{old}排在第二位。别忘了{unchanged}。'
        endings = ('最终取刚才那个次选，其他要求也留着。', '最终就定刚才的首选，其他要求也留着。')
        rows.append((f'{name}-名次', (first, second), endings, choices))
    return tuple(rows)


