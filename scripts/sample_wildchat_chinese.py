"""Sample screened Chinese multi-turn WildChat locally, without approval."""
import argparse
import collections
import hashlib
import json
import random
import re
from pathlib import Path

import pyarrow.parquet as pq

ROOT = Path(__file__).resolve().parents[1]
RISK = re.compile(r'https?://|[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}|(?<!\d)\d{7,}(?!\d)|电话|手机号|身份证|住址|家庭地址|银行卡|信用卡|微信号|邮箱|密码|病史|患者|诊断|病历|个人信息|自杀|自残|自傷', re.I)


def sha(path):
    with path.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--input', required=True)
    p.add_argument('--sha256', required=True)
    p.add_argument('--output', required=True)
    p.add_argument('--seed', type=int, default=751109)
    p.add_argument('--count', type=int, default=30)
    args = p.parse_args()
    source, output = ROOT / args.input, ROOT / args.output
    if output.exists():
        raise FileExistsError(output)
    if not 1 <= args.count <= 200 or sha(source) != args.sha256:
        raise ValueError('Invalid sample size or source checksum')
    rng, seen, sample, counts = random.Random(args.seed), set(), [], collections.Counter()
    columns = ['language', 'turn', 'toxic', 'redacted'] + [
        'conversation.list.element.' + field for field in ('content', 'role', 'toxic', 'redacted')]
    for batch in pq.ParquetFile(source).iter_batches(batch_size=128, columns=columns):
        for row in batch.to_pylist():
            if row['language'] != 'Chinese':
                continue
            counts['chinese_labeled'] += 1
            if row['toxic'] is not False or row['redacted'] is not False:
                counts['source_flag_or_missing'] += 1
                continue
            conversation = row['conversation'] or []
            if not 4 <= len(conversation) <= 8 or len(conversation) % 2:
                counts['turn_count'] += 1
                continue
            if any(turn.get('role') != ('user' if i % 2 == 0 else 'assistant') or
                   turn.get('toxic') is not False or turn.get('redacted') is not False
                   for i, turn in enumerate(conversation)):
                counts['roles_or_turn_flags'] += 1
                continue
            messages = [{'role': turn['role'], 'content': (turn.get('content') or '').strip()}
                        for turn in conversation]
            if any(not m['content'] or len(m['content']) > 1800 or RISK.search(m['content']) for m in messages):
                counts['content_or_pattern'] += 1
                continue
            text = ''.join(m['content'] for m in messages)
            han = sum('\u4e00' <= c <= '\u9fff' for c in text)
            if han / len(text) < .40:
                counts['chinese_ratio'] += 1
                continue
            identity = hashlib.sha256(json.dumps(messages, ensure_ascii=False, sort_keys=True).encode('utf8')).hexdigest()
            if identity in seen:
                counts['duplicate'] += 1
                continue
            seen.add(identity)
            counts['eligible'] += 1
            # Only role and content leave the loop; no account, network or location fields.
            item = dict(content_sha256=identity, messages=messages)
            if len(sample) < args.count:
                sample.append(item)
            else:
                i = rng.randrange(counts['eligible'])
                if i < args.count:
                    sample[i] = item
    if len(sample) != args.count:
        raise ValueError('Insufficient screened records')
    result = dict(status='sample_for_review_not_approved_for_training', source_sha256=args.sha256,
                  evaluator_sha256=sha(Path(__file__)), seed=args.seed, counts=counts,
                  sample_size=len(sample), samples=sample,
                  scope='One shard; Chinese label and simple filters are not proof of language, privacy, safety, accuracy or generalization. Assistant turns were generated by external models; no model is called at inference.')
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open('x', encoding='utf8') as f:
        json.dump(result, f, ensure_ascii=False, indent=2)
    print(json.dumps({k: v for k, v in result.items() if k != 'samples'}, ensure_ascii=False))


if __name__ == '__main__':
    main()
