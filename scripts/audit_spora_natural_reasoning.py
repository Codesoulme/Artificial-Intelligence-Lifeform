class NaturalReplyLimit(StoppingCriteria):
    """Track a delimiter that was generated by the model itself."""

    def __init__(self, prompt_length, delimiter):
        self.prompt_length = prompt_length
        self.delimiter = delimiter
        self.end = None
        self.answer_started = None

    def __call__(self, input_ids, scores, **kwargs):
        count = input_ids.shape[-1] - self.prompt_length
        if self.end is None and int(input_ids[0, -1]) == self.delimiter:
            self.end = count
            self.answer_started = perf_counter()
        if self.end is None:
            return count >= REASONING_BUDGET
        return count - self.end >= ANSWER_BUDGET


@torch.inference_mode()
def generate(model, tokenizer, case, *, native, sampled, seed):
    messages = [{'role': role, 'content': content} for role, content in case.history]
    messages.append({'role': 'user', 'content': case.question})
    prompt = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    if not prompt.endswith('<think>\n'):
        raise ValueError('Expected the saved DeepSeek conversation template')
    if not native:
        prompt += '</think>\n\n'
    inputs = tokenizer(prompt, add_special_tokens=False, return_tensors='pt').to(model.device)
    length = inputs.input_ids.shape[-1]
    delimiter, = tokenizer.encode('</think>', add_special_tokens=False)
    leading, = tokenizer.encode('<think>', add_special_tokens=False)
    limit = NaturalReplyLimit(length, delimiter) if native else None
    options = {'temperature': .6, 'top_p': .95, 'top_k': 0} if sampled else {
        'temperature': None, 'top_p': None, 'top_k': None,
    }
    torch.manual_seed(seed)
    torch.cuda.synchronize()
    started = perf_counter()
    generated = model.generate(
        **inputs, **options, use_cache=True, do_sample=sampled,
        pad_token_id=tokenizer.pad_token_id, eos_token_id=tokenizer.eos_token_id,
        max_new_tokens=ANSWER_BUDGET + (REASONING_BUDGET if native else 0),
        stopping_criteria=[limit] if limit else None,
    )[0, length:].tolist()
    torch.cuda.synchronize()
    ended = perf_counter()
    boundary = limit.end if limit else 0
    answer_ids = generated[boundary:] if boundary is not None else []
    if delimiter in answer_ids or leading in answer_ids:
        answer_ids = []
    eos = bool(answer_ids and answer_ids[-1] == tokenizer.eos_token_id)
    answer = tokenizer.decode(answer_ids, skip_special_tokens=True).strip()
    thinking = (len(generated) if boundary is None else boundary - 1) if native else 0
    return {'answer': answer, 'visible_eos': bool(answer and eos), 'native_close': native and boundary is not None,
            'thinking_tokens': thinking, 'answer_tokens': len(answer_ids) - int(eos),
            'seconds': ended - started,
            'before_visible_seconds': (limit.answer_started or ended) - started if limit else 0.}


def main(args):
    torch.set_num_threads(2)
    torch.cuda.reset_peak_memory_stats()
    if args.output.exists():
        raise FileExistsError(args.output)
    source_paths = (base.MODEL / 'model.safetensors', base.MODEL / 'tokenizer.json',
                    base.MODEL / 'tokenizer_config.json', Path(__file__))
    sources = {str(path): digest(path) for path in source_paths}
    if sources[str(source_paths[0])] != base.WEIGHT_SHA:
        raise ValueError('The local entry backbone differs from the fixed DeepSeek weights')
    model = load_full_streamed()
    tokenizer = base.AutoTokenizer.from_pretrained(base.MODEL, local_files_only=True, trust_remote_code=False)
    rows, summary = [], {}
    modes = (('direct_greedy', False, False), ('direct_sampled', False, True), ('native_sampled', True, True))
    for index, case in enumerate(CASES):
        answers = {}
        for mode, native, sampled in modes:
            result = generate(model, tokenizer, case, native=native, sampled=sampled, seed=SEED + index)
            answers[mode] = result
            summary.setdefault(mode, Counter()).update(
                responses=1, nonempty=bool(result['answer']), visible_eos=result['visible_eos'],
                native_close=result['native_close'],
            )
        rows.append({**asdict(case), 'answers': answers})
        print(case.name, {mode: (value['thinking_tokens'], value['answer_tokens'], value['visible_eos'])
                          for mode, value in answers.items()}, flush=True)
    if any(digest(path) != sources[str(path)] for path in source_paths):
        raise ValueError('A sealed input artifact changed')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    store_json(args.output, {'sources': sources, 'answer_budget': ANSWER_BUDGET, 'reasoning_budget': REASONING_BUDGET,
                             'rows': rows, 'summary': summary, 'peak_bytes': torch.cuda.max_memory_allocated()})


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    main(parser.parse_args())
