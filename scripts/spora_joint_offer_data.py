def scenes(forms, names, group):
    rows = []
    for index, (start, options, tail) in enumerate(forms):
        for first, second in names:
            opening, ending = (part.format(a=first, b=second) for part in (start, tail))
            for state, template in enumerate(options):
                decision = template.format(a=first, b=second)
                reply = '。'.join(part for part in (opening, decision, ending) if part) + '。'
                rows.append({'key': f'{group}/{index}/{first}/{state}', 'group': group,
                             'reply': reply, 'targets': (first, second), 'state': state})
    return rows


